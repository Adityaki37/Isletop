import test from "node:test";
import assert from "node:assert/strict";
import { guestPlayerName, randomPlayerName, readablePlayerName } from "../lib/player-name";
import { usernameKey } from "../lib/account-crypto";
import { USERNAME_MAX_LENGTH } from "../lib/username";

test("random player names contain only words and fit username constraints", () => {
  const names = Array.from({ length: 1000 }, () => randomPlayerName());
  for (const name of names) {
    assert(name.length <= USERNAME_MAX_LENGTH);
    assert.match(name, /^[A-Z][a-z]+[A-Z][a-z]+$/);
    assert.equal(usernameKey(name), name.toLowerCase());
  }
});

test("guest initialization replaces saved disposable QA names while preserving chosen names", () => {
  for (const saved of [null, "", "Live QA 1009/0", "Live QA 1791431124799/0"])
    assert.match(guestPlayerName(saved), /^[A-Z][a-z]+[A-Z][a-z]+$/);
  for (const chosen of ["IslandPlayer", "SunnySailor", "Live QA Fan", "Custom_Name"])
    assert.equal(guestPlayerName(chosen), chosen);
  assert.equal(guestPlayerName("SunnySailor_cb3e50b8"), "SunnySailor");
});

test("older autogenerated suffixes are removed without changing custom names", () => {
  assert.equal(readablePlayerName("SunnySailor_cb3e50b8"), "SunnySailor");
  assert.equal(readablePlayerName("sunnysailor_cb3e50b8"), "sunnysailor");
  for (const custom of ["googleqa_oct7", "MyName_cb3e50b8", "SunnySailor", "Custom_Name", "SunnySailor_123"])
    assert.equal(readablePlayerName(custom), custom);
});
